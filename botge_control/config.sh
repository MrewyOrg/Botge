#!/bin/bash

: "${BOTGE_CONTROL_NAME:?Control name must be set before loading config.}"
readonly BOTGE_CONTROL_NAME
readonly BOTGE_CONTROL_USER="$BOTGE_CONTROL_NAME"
readonly BOTGE_CONTROL_USER_HOME="/home/$BOTGE_CONTROL_USER"
readonly BOTGE_CONTROL_GROUP="${BOTGE_CONTROL_NAME}_trigger"
readonly BOTGE_CONTROL_UID=4242

readonly BOTGE_DIR="$BOTGE_CONTROL_USER_HOME/botge"
readonly BOTGE_RUNTIME_DIR="/run/user/$BOTGE_CONTROL_UID"

export BOTGE_CONTROL_USER BOTGE_CONTROL_USER_HOME BOTGE_CONTROL_GROUP BOTGE_CONTROL_UID
export BOTGE_DIR BOTGE_RUNTIME_DIR
